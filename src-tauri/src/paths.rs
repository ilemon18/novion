use std::path::{Path, PathBuf};

use tauri::{AppHandle, Manager, Runtime};

use crate::config::{self, Storage};
use crate::error::{AppError, AppResult};

pub struct Paths {
    pub root: PathBuf,
}

/// `~/Library/Mobile Documents/com~apple~CloudDocs/Novion` — the iCloud Drive
/// folder every Mac signed into the same Apple ID syncs.
///
/// macOS only: on other systems this path never exists, `icloud_available`
/// reports false and the workspace silently stays local (the UI hides the
/// switch entirely, see `StorageState::icloud_supported`).
pub const ICLOUD_REL: &str = "Library/Mobile Documents/com~apple~CloudDocs/Novion";

pub fn document_dir<R: Runtime>(app: &AppHandle<R>) -> AppResult<PathBuf> {
    app.path()
        .document_dir()
        .map_err(|e| AppError::new("no_document_dir", format!("无法获取用户文档目录：{e}")))
}

pub fn local_root<R: Runtime>(app: &AppHandle<R>) -> AppResult<PathBuf> {
    Ok(document_dir(app)?.join("Novion"))
}

/// Where exports and backups land: `~/Downloads/Novion`, falling back to the
/// documents folder on systems without a Downloads directory.
pub fn export_root<R: Runtime>(app: &AppHandle<R>) -> PathBuf {
    app.path()
        .download_dir()
        .or_else(|_| app.path().document_dir())
        .map(|dir| dir.join("Novion"))
        .unwrap_or_else(|_| PathBuf::from("Novion"))
}

pub fn icloud_root<R: Runtime>(app: &AppHandle<R>) -> AppResult<PathBuf> {
    let home = app
        .path()
        .home_dir()
        .map_err(|e| AppError::new("no_home_dir", format!("无法获取用户目录：{e}")))?;
    Ok(home.join(ICLOUD_REL))
}

/// True when iCloud Drive is actually present (signed in + enabled).
pub fn icloud_available<R: Runtime>(app: &AppHandle<R>) -> bool {
    let Ok(root) = icloud_root(app) else {
        return false;
    };
    match root.parent() {
        Some(parent) => parent.is_dir(),
        None => false,
    }
}

/// The directory every command reads and writes.
///
/// Falls back to the local folder when iCloud was selected but is no longer
/// reachable, so the app keeps working instead of erroring on every action.
pub fn workspace_root<R: Runtime>(app: &AppHandle<R>) -> AppResult<PathBuf> {
    match config::current(app) {
        Storage::Local => local_root(app),
        Storage::Icloud => {
            if icloud_available(app) {
                icloud_root(app)
            } else {
                local_root(app)
            }
        }
    }
}

impl Paths {
    pub fn new(root: PathBuf) -> Self {
        Self { root }
    }

    pub async fn ensure_dirs(&self) -> AppResult<()> {
        for dir in [&self.root, &self.docs_dir(), &self.assets_dir()] {
            tokio::fs::create_dir_all(dir)
                .await
                .map_err(|e| AppError::io(&format!("创建目录 {} 失败", dir.display()), e))?;
        }
        Ok(())
    }

    pub fn workspace_file(&self) -> PathBuf {
        self.root.join("workspace.json")
    }

    pub fn docs_dir(&self) -> PathBuf {
        self.root.join("docs")
    }

    pub fn assets_dir(&self) -> PathBuf {
        self.root.join("assets")
    }

    /// `docs/<id>.json` — the id is validated so it can never escape `docs/`.
    pub fn doc_file(&self, id: &str) -> AppResult<PathBuf> {
        validate_id(id)?;
        Ok(self.docs_dir().join(format!("{id}.json")))
    }

    /// `history/<docId>/` — one rolling snapshot file per version.
    pub fn history_dir(&self) -> PathBuf {
        self.root.join("history")
    }

    pub fn history_doc_dir(&self, id: &str) -> AppResult<PathBuf> {
        validate_id(id)?;
        Ok(self.history_dir().join(id))
    }

    /// Resolve a workspace-relative asset path (`assets/x.png`).
    ///
    /// Backslashes are accepted and normalised: a document written on Windows
    /// may carry `assets\img.png`, which means the same file.
    pub fn asset_file(&self, rel: &str) -> AppResult<PathBuf> {
        let normalized = rel.trim().replace('\\', "/");
        let rel = normalized.trim_start_matches('/');
        if !rel.starts_with("assets/") || rel.contains("..") {
            return Err(AppError::invalid(format!("非法的资源路径：{rel}")));
        }
        let path = self.root.join(rel);
        if !path.starts_with(self.assets_dir()) {
            return Err(AppError::invalid("资源路径越界"));
        }
        Ok(path)
    }
}

/// Ids are generated by this app: `d_ab12cd34ef`, `f_1a2b`, `img_9f8e...`
pub fn validate_id(id: &str) -> AppResult<()> {
    let ok = !id.is_empty()
        && id.len() <= 80
        && id
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '-');
    if ok {
        Ok(())
    } else {
        Err(AppError::invalid(format!("非法 id：{id}")))
    }
}

pub fn short_id() -> String {
    let raw = uuid::Uuid::new_v4().simple().to_string();
    raw[..10].to_string()
}

/// Normalise a user supplied file name into a safe extension.
pub fn extension_of(name_hint: &str) -> String {
    let ext = name_hint
        .rsplit('.')
        .next()
        .filter(|e| *e != name_hint)
        .unwrap_or("png")
        .to_ascii_lowercase();
    match ext.as_str() {
        "png" | "jpg" | "jpeg" | "gif" | "webp" | "avif" | "svg" | "bmp" | "heic" => ext,
        _ => "png".to_string(),
    }
}

pub fn to_display(path: &Path) -> String {
    path.to_string_lossy().to_string()
}